/**
 * Generates TypeScript types from the authentik OpenAPI schema.
 *
 * Usage:
 *   pnpm generate:types                       # pinned tag (AUTHENTIK_SCHEMA_TAG or default)
 *   pnpm generate:types --url <schema url>    # e.g. https://auth.example.com/api/v3/schema/
 *
 * A live instance URL requires AUTHENTIK_TOKEN in the environment.
 */
import { writeFile } from "node:fs/promises";
import openapiTS, { astToString } from "openapi-typescript";

const DEFAULT_TAG = "version/2026.8.4";
const OUTPUT = new URL("../src/lib/authentik/schema.d.ts", import.meta.url);

function resolveSchemaUrl(): string {
  const flagIndex = process.argv.indexOf("--url");
  const explicit = flagIndex === -1 ? undefined : process.argv[flagIndex + 1];
  if (explicit) return explicit;
  const tag = process.env.AUTHENTIK_SCHEMA_TAG ?? DEFAULT_TAG;
  return `https://raw.githubusercontent.com/goauthentik/authentik/refs/tags/${tag}/schema.yml`;
}

async function fetchSchema(url: string): Promise<string> {
  const headers: Record<string, string> = { Accept: "application/yaml, application/json" };
  const isGithub = url.startsWith("https://raw.githubusercontent.com/");
  if (!isGithub && process.env.AUTHENTIK_TOKEN) {
    headers.Authorization = `Bearer ${process.env.AUTHENTIK_TOKEN}`;
  }
  const response = await fetch(url, { headers });
  if (!response.ok) throw new Error(`Failed to fetch schema (${response.status}) from ${url}`);
  return response.text();
}

async function main(): Promise<void> {
  const url = resolveSchemaUrl();
  console.log(`Fetching schema: ${url}`);
  const ast = await openapiTS(await fetchSchema(url));
  const header = `// Generated by scripts/generate-types.ts from ${url}\n// Do not edit manually.\n\n`;
  await writeFile(OUTPUT, header + astToString(ast));
  console.log(`Wrote ${OUTPUT.pathname}`);
}

main().catch((error: unknown) => {
  console.error(error instanceof Error ? error.message : error);
  process.exit(1);
});
