import { z } from "zod";
import { readableTextOn } from "./wcag";

const hex = z.string().regex(/^#([0-9a-f]{3}|[0-9a-f]{6})$/i, "use #rgb or #rrggbb");

const palette = z.object({
  primary: hex,
  primaryHover: hex.optional(),
  accent: hex.optional(),
  background: hex,
  surface: hex,
  text: hex,
  textMuted: hex.optional(),
  danger: hex.optional(),
  success: hex.optional(),
});

export const designTokens = z.object({
  light: palette,
  dark: palette.optional(),
  borderRadius: z
    .string()
    .regex(/^\d+(\.\d+)?(rem|em|px)$/)
    .default("0.375rem"),
  // Both are pasted into generated CSS, so characters that could close a value or rule are refused.
  fontFamily: z
    .string()
    .max(200)
    .regex(/^[\w\s,'"-]+$/, "font names, commas and quotes only")
    .optional()
    .describe('e.g. "Inter, system-ui, sans-serif"'),
  fontUrl: z
    .url({ protocol: /^https$/ })
    .regex(/^[^\s"\\]+$/, "URL must not contain quotes, backslashes or whitespace")
    .optional()
    .describe("Stylesheet URL, e.g. Google Fonts css2 link"),
  includePartOverrides: z
    .boolean()
    .default(false)
    .describe("Add ::part() tweaks (library cards, login header, locale selector)"),
});

export type DesignTokens = z.infer<typeof designTokens>;
type Palette = z.infer<typeof palette>;

/**
 * Maps one palette to PatternFly (v4 and v5 names) and authentik variables.
 * authentik's UI is built on PatternFly, so its global variables are the stable hook.
 */
function variables(p: Palette, radius: string, font?: string): string[] {
  const hover = p.primaryHover ?? p.primary;
  const onPrimary = readableTextOn(p.primary);
  const pairs: [string, string | undefined][] = [
    ["primary-color--100", p.primary],
    ["primary-color--200", hover],
    ["link--Color", p.primary],
    ["link--Color--hover", hover],
    ["active-color--100", p.accent ?? p.primary],
    ["BackgroundColor--100", p.surface],
    ["BackgroundColor--200", p.background],
    ["BackgroundColor--light-100", p.surface],
    ["Color--100", p.text],
    ["Color--200", p.textMuted],
    ["danger-color--100", p.danger],
    ["success-color--100", p.success],
    ["BorderRadius--sm", radius],
    ["BorderRadius--lg", `calc(${radius} * 2)`],
    ["FontFamily--sans-serif", font],
    ["FontFamily--heading--sans-serif", font],
    ["FontFamily--text", font],
    ["FontFamily--heading", font],
  ];
  const lines: string[] = [];
  for (const [name, value] of pairs) {
    if (!value) continue;
    lines.push(`  --pf-global--${name}: ${value};`, `  --pf-v5-global--${name}: ${value};`);
  }
  lines.push(`  --ak-accent: ${p.accent ?? p.primary};`, `  --ak-mcp-on-primary: ${onPrimary};`);
  return lines;
}

function buttonRules(selectorPrefix: string): string {
  return `${selectorPrefix} {
  --pf-c-button--m-primary--BackgroundColor: var(--pf-global--primary-color--100);
  --pf-c-button--m-primary--hover--BackgroundColor: var(--pf-global--primary-color--200);
  --pf-c-button--m-primary--Color: var(--ak-mcp-on-primary);
  --pf-v5-c-button--m-primary--BackgroundColor: var(--pf-v5-global--primary-color--100);
  --pf-v5-c-button--m-primary--hover--BackgroundColor: var(--pf-v5-global--primary-color--200);
  --pf-v5-c-button--m-primary--Color: var(--ak-mcp-on-primary);
}`;
}

const PART_OVERRIDES = `/* Fine-tuning through exposed parts (stable across upgrades when the part exists). */
ak-library::part(card-header-icon) {
  border-radius: var(--pf-global--BorderRadius--sm);
}
ak-flow-executor::part(locale-select) {
  border-radius: var(--pf-global--BorderRadius--sm);
}`;

const ACCESSIBILITY = `@media (prefers-contrast: more) {
  :root {
    --pf-global--BorderWidth--sm: 2px;
    --pf-v5-global--BorderWidth--sm: 2px;
    --pf-global--link--TextDecoration: underline;
  }
}
@media (prefers-reduced-motion: reduce) {
  *, *::before, *::after {
    animation-duration: 0.01ms !important;
    transition-duration: 0.01ms !important;
    scroll-behavior: auto !important;
  }
}
@media (prefers-reduced-transparency: reduce) {
  * {
    backdrop-filter: none !important;
  }
}`;

/** Generates variable-based CSS for light and (optionally) dark themes. */
export function generateCss(tokens: DesignTokens): string {
  const sections: string[] = [];
  if (tokens.fontUrl) sections.push(`@import url("${tokens.fontUrl}");`);
  sections.push(
    `/* Generated by authentik-mcp from brand design tokens. Edit tokens, not this block. */`,
    `:root {\n${variables(tokens.light, tokens.borderRadius, tokens.fontFamily).join("\n")}\n}`,
  );
  if (tokens.dark) {
    sections.push(
      `html[data-theme="dark"] {\n${variables(tokens.dark, tokens.borderRadius, tokens.fontFamily).join("\n")}\n}`,
    );
  }
  sections.push(buttonRules(':root, html[data-theme="dark"]'));
  if (tokens.fontFamily) sections.push(`body {\n  font-family: ${tokens.fontFamily};\n}`);
  if (tokens.includePartOverrides) sections.push(PART_OVERRIDES);
  sections.push(ACCESSIBILITY);
  return sections.join("\n\n");
}
